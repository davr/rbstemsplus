int library_list(library *l, FILE *out, char *why, size_t n) {
    /* parents before children: walk down from "root", each level by Seq */
    static const char *q =
        "WITH RECURSIVE tree(ID, ParentID, Name, Attribute, Seq, depth, path) AS ("
        "  SELECT ID, ParentID, Name, Attribute, Seq, 0, printf('%010d', Seq) FROM djmdPlaylist"
        "   WHERE ParentID = 'root' AND rb_local_deleted = 0"
        "  UNION ALL"
        "  SELECT p.ID, p.ParentID, p.Name, p.Attribute, p.Seq, t.depth + 1,"
        "         t.path || '/' || printf('%010d', p.Seq) FROM djmdPlaylist p JOIN tree t ON p.ParentID = t.ID"
        "   WHERE p.rb_local_deleted = 0 AND t.depth < 64)"
        " SELECT t.ID, t.ParentID, t.Name, t.Attribute,"
        "  (SELECT count(*) FROM djmdSongPlaylist s WHERE s.PlaylistID = t.ID AND s.rb_local_deleted = 0)"
        " FROM tree t ORDER BY t.path";
    if (begin(l, why, n)) return -1;
    sqlite3_stmt *st = NULL;
    if (sqlite3_prepare_v2(l->db, q, -1, &st, NULL) != SQLITE_OK) { fail(l->db, "can't list its playlists", why, n); end(l); return -1; }
    int rc;
    while ((rc = sqlite3_step(st)) == SQLITE_ROW) {
        int attr = sqlite3_column_int(st, 3);
        fprintf(out, "{\"playlist\":");
        json_str(out, (const char *)sqlite3_column_text(st, 0));
        fprintf(out, ",\"parent\":");
        json_str(out, (const char *)sqlite3_column_text(st, 1));
        fprintf(out, ",\"name\":");
        json_str(out, (const char *)sqlite3_column_text(st, 2));
        fprintf(out, ",\"kind\":\"%s\",\"tracks\":%d}\n", kind(attr), attr == 0 ? sqlite3_column_int(st, 4) : 0);
    }
    if (rc != SQLITE_DONE) fail(l->db, "can't list its playlists", why, n);
    sqlite3_finalize(st);
    end(l);
    fflush(out);
    return rc == SQLITE_DONE ? 0 : -1;
}

int library_tracks(library *l, const char *id, char ***paths, size_t *count, char *why, size_t n) {
    *paths = NULL;
    *count = 0;
    if (begin(l, why, n)) return -1;
    sqlite3_stmt *st = NULL;
    int ret = -1, rc;
    if (sqlite3_prepare_v2(l->db, "SELECT Attribute, Name FROM djmdPlaylist WHERE ID = ? AND rb_local_deleted = 0",
                           -1, &st, NULL) != SQLITE_OK) { fail(l->db, "can't read its playlists", why, n); goto out; }
    sqlite3_bind_text(st, 1, id, -1, SQLITE_TRANSIENT);
    rc = sqlite3_step(st);
    if (rc != SQLITE_ROW) {
        if (rc == SQLITE_DONE) snprintf(why, n, "rekordbox's library has no playlist %s", id);
        else fail(l->db, "can't read its playlists", why, n);
        goto out;
    }
    int attr = sqlite3_column_int(st, 0);
    if (attr != 0) {
        snprintf(why, n, "%s is %s, not a playlist", (const char *)sqlite3_column_text(st, 1),
                 attr == 1 ? "a folder" : attr == 4 ? "an intelligent playlist" : "not a plain playlist");
        goto out;
    }
    sqlite3_finalize(st);
    /* the query measured against rekordbox's own list: in order, duplicates included */
    if (sqlite3_prepare_v2(l->db,
                           "SELECT c.FolderPath FROM djmdSongPlaylist s JOIN djmdContent c ON c.ID = s.ContentID"
                           " WHERE s.PlaylistID = ? AND s.rb_local_deleted = 0 ORDER BY s.TrackNo",
                           -1, &st, NULL) != SQLITE_OK) { st = NULL; fail(l->db, "can't read the playlist", why, n); goto out; }
    sqlite3_bind_text(st, 1, id, -1, SQLITE_TRANSIENT);
    size_t cap = 64;
    char **p = malloc(sizeof(char *) * cap);
    if (!p) { snprintf(why, n, "out of memory"); goto out; }
    while ((rc = sqlite3_step(st)) == SQLITE_ROW) {
        const char *path = (const char *)sqlite3_column_text(st, 0);
        if (!path || !((((path[0] | 32) >= 'a' && (path[0] | 32) <= 'z') && path[1] == ':') || (path[0] == '\\' && path[1] == '\\'))) continue;   /* a streaming track: left alone */
        size_t k = 0;
        while (k < *count && strcmp(p[k], path)) k++;     /* each path once, first place kept */
        if (k < *count) continue;
        if (*count == cap) {
            char **q = realloc(p, sizeof(char *) * (cap *= 2));
            if (!q) { rc = SQLITE_NOMEM; break; }
            p = q;
        }
        if (!(p[*count] = strdup(path))) { rc = SQLITE_NOMEM; break; }
        (*count)++;
    }
    if (rc != SQLITE_DONE) {
        if (rc == SQLITE_NOMEM) snprintf(why, n, "out of memory");
        else fail(l->db, "can't read the playlist", why, n);
        for (size_t k = 0; k < *count; k++) free(p[k]);
        free(p);
        *count = 0;
        goto out;
    }
    *paths = p;
    ret = 0;
out:
    sqlite3_finalize(st);
    end(l);
    return ret;
}
