library *library_open(const char *path, char *why, size_t n) {
    sqlite3 *db = NULL;
    if (load_sqlite(why, n)) return NULL;
    if (sqlite3_open_v2(path, &db, SQLITE_OPEN_READONLY | SQLITE_OPEN_NOMUTEX, NULL) != SQLITE_OK) {
        fail(db, "can't open it", why, n);
        sqlite3_close(db);
        return NULL;
    }
    unsigned char key[LIBKEY_LEN];
    for (int i = 0; i < LIBKEY_LEN; i++) key[i] = (unsigned char)(LIBKEY[i] - 0x5a - 13 * i);
    int rc = sqlite3_key(db, key, LIBKEY_LEN);
    memset(key, 0, sizeof key);
    __asm__ volatile("" : : "r"(key) : "memory");     /* the wipe stays */
    /* the first read proves the key (SQLCipher only checks it then) */
    if (rc == SQLITE_OK) rc = sqlite3_busy_timeout(db, 5000);
    if (rc == SQLITE_OK) rc = sqlite3_exec(db, "SELECT count(*) FROM sqlite_master", NULL, NULL, NULL);
    if (rc != SQLITE_OK) {
        fail(db, rc == SQLITE_NOTADB ? "not a rekordbox library this helper can read" : "can't read it", why, n);
        sqlite3_close(db);
        return NULL;
    }
    library *l = malloc(sizeof *l);
    if (!l) { sqlite3_close(db); snprintf(why, n, "out of memory"); return NULL; }
    l->db = db;
    return l;
}

void library_close(library *l) {
    if (!l) return;
    sqlite3_close(l->db);
    free(l);
}

static void json_str(FILE *f, const char *s) {
    fputc('"', f);
    for (const unsigned char *p = (const unsigned char *)(s ? s : ""); *p; p++) {
        if (*p == '"' || *p == '\\') fprintf(f, "\\%c", *p);
        else if (*p < 0x20) fprintf(f, "\\u%04x", *p);
        else fputc(*p, f);
    }
    fputc('"', f);
}

