#!/usr/bin/env python3
"""Writes tests/config-fixtures-windows.txt from tests/config-fixtures.txt (the macOS fixtures):
the same cases with Windows paths, for the Windows bridge (bridge/win/tests/run.sh) and the Windows
app's tests (windows/RBStemsPlus.Tests). Run it again after changing config-fixtures.txt:

    python3 tests/make_windows_fixtures.py

The mapping: "/Volumes/<vol>/.../RB Stems Plus Cache.noindex" becomes "E:\\<vol>\\...\\RB Stems Plus
Cache" (the folder has no ".noindex" on Windows), and "/" in a cache_dir becomes "\\". Cases whose
verdict depends on a length are recomputed for the Windows path (the 700-byte path, the
1023/1024/1025-byte lines), and the root folder is allowed on Windows (a drive's root). Windows-only
cases are appended at the end.
"""
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(here, "config-fixtures.txt")
OUT = os.path.join(here, "config-fixtures-windows.txt")
MAC_FOLDER = "RB Stems Plus Cache.noindex"
WIN_FOLDER = "RB Stems Plus Cache"


def esc_path(p):
    """a Windows path as fixture text (backslashes escaped)"""
    return p.replace("\\", "\\\\")


def mac_to_win(text):
    """every macOS cache path in a fixture's text (content or dir=) as a Windows one"""
    def one(m):
        p = m.group(0)
        p = p.replace(MAC_FOLDER, WIN_FOLDER).replace("rb stems plus cache.noindex", "rb stems plus cache")
        if p.startswith("/Volumes/"):
            p = "E:/" + p[len("/Volumes/"):]
        elif p.startswith("Volumes/"):
            p = "E/" + p[len("Volumes/"):]                  # stays relative: no drive letter
        # the fixture's own escapes (\t, \*N.c) stay as they are: only "/" becomes an escaped "\\"
        return p.replace("/", "\\\\")
    # a path runs from "/Volumes/" or "Volumes/" (or "/RB") to the end of the folder's name (or a
    # quote, a newline escape, a tab escape or the end)
    return re.sub(r"/?Volumes/(?:[^\"'\\\n]|\\\*\d+\.[^\\]|\\t)*?(?:(?i:rb stems plus cache\.noindex)/?|(?=[\"']|\\n|$))", one, text)


def length_case(name, expected, content):
    """the cases whose verdict depends on a length, rebuilt for Windows"""
    id_line = "cache_id=0F8C2D3A-1B2C-4D5E-8F90-1A2B3C4D5E6F\\n"
    if name in ("path-700", "path-701"):
        # E:\ + N a's + \RB Stems Plus Cache = 700 (or 701) bytes
        n = (700 if name == "path-700" else 701) - len("E:\\") - len("\\" + WIN_FOLDER)
        p = "E:\\\\\\*%d.a\\\\%s" % (n, WIN_FOLDER)
        ok = name == "path-700"
        exp = "enabled=1 max_gb=20 max_days=60 location=" + ("chosen dir=E:\\\\\\*%d.a\\\\%s" % (n, WIN_FOLDER.replace(" ", "%20")) if ok else "malformed")
        return exp, 'cache_dir="%s"\\n%s' % (p, id_line)
    m = re.match(r"line-(\d+)(-crlf)?$", name)
    if m:
        total, crlf = int(m.group(1)), bool(m.group(2))
        line = 'cache_dir="E:\\GLS\\%s"' % WIN_FOLDER
        pad = total - len(line) - (1 if crlf else 0)
        ok = total <= 1024
        exp = "enabled=1 max_gb=20 max_days=60 location=" + ("chosen dir=E:\\\\GLS\\\\RB%20Stems%20Plus%20Cache" if ok else "malformed")
        return exp, '%s\\*%d. %s\\n%s' % (esc_path(line), pad, "\\r" if crlf else "", id_line)
    if name == "djs-ssd":
        p = "E:\\\\DJ's SSD\\\\Sets #1\\\\" + WIN_FOLDER
        return ("enabled=1 max_gb=20 max_days=60 location=chosen dir=" + p.replace(" ", "%20"),
                'cache_dir="%s"\\n%s' % (p, id_line))
    if name == "root-folder":
        # a drive's root is allowed on Windows; without a drive letter it isn't absolute
        return ("enabled=1 max_gb=20 max_days=60 location=malformed",
                'cache_dir="\\\\%s"\\n%s' % (WIN_FOLDER, id_line))
    return None


def main():
    out = ["# GENERATED by tests/make_windows_fixtures.py from tests/config-fixtures.txt: edit that file (or the",
           "# Windows-only cases in the script) and run the script again. The same format as config-fixtures.txt;",
           "# paths are Windows paths (backslashes escaped as \\\\), the chosen folder is \"RB Stems Plus Cache\"."]
    for line in open(SRC, encoding="utf-8").read().split("\n"):
        if not line or line.startswith("#"):
            continue
        name, expected, content = (line.split("\t", 2) + [""])[:3]
        lc = length_case(name, expected, content)
        if lc:
            expected, content = lc
        else:
            content = mac_to_win(content)
            expected = " ".join("dir=" + mac_to_win(w[4:].replace("%20", " ")).replace(" ", "%20") if w.startswith("dir=") else w
                                for w in expected.split())
        out.append("\t".join([name, expected, content]) if content or line.count("\t") >= 2 else "\t".join([name, expected]))
    idl = "cache_id=0F8C2D3A-1B2C-4D5E-8F90-1A2B3C4D5E6F\\n"
    chosen = "enabled=1 max_gb=20 max_days=60 location=chosen dir="
    bad = "enabled=1 max_gb=20 max_days=60 location=malformed"
    extra = [
        ("win-drive-root", chosen + "E:\\\\RB%20Stems%20Plus%20Cache", 'cache_dir="E:\\\\RB Stems Plus Cache"\\n' + idl),
        ("win-lowercase-drive", chosen + "e:\\\\GLS\\\\RB%20Stems%20Plus%20Cache", 'cache_dir="e:\\\\GLS\\\\RB Stems Plus Cache"\\n' + idl),
        ("win-forward-slashes", bad, 'cache_dir="E:/GLS/RB Stems Plus Cache"\\n' + idl),
        ("win-unc", bad, 'cache_dir="\\\\\\\\server\\\\share\\\\RB Stems Plus Cache"\\n' + idl),
        ("win-long-prefix", bad, 'cache_dir="\\\\\\\\?\\\\E:\\\\GLS\\\\RB Stems Plus Cache"\\n' + idl),
        ("win-no-backslash", bad, 'cache_dir="E:RB Stems Plus Cache"\\n' + idl),
        ("win-reserved-char", bad, 'cache_dir="E:\\\\GL?S\\\\RB Stems Plus Cache"\\n' + idl),
        ("win-colon", bad, 'cache_dir="E:\\\\GL:S\\\\RB Stems Plus Cache"\\n' + idl),
        ("win-trailing-dot", bad, 'cache_dir="E:\\\\GLS.\\\\RB Stems Plus Cache"\\n' + idl),
        ("win-trailing-space", bad, 'cache_dir="E:\\\\GLS \\\\RB Stems Plus Cache"\\n' + idl),
        ("win-mac-folder-name", bad, 'cache_dir="E:\\\\GLS\\\\RB Stems Plus Cache.noindex"\\n' + idl),
        ("win-mac-path", bad, 'cache_dir="/Volumes/GLS/RB Stems Plus Cache.noindex"\\n' + idl),
    ]
    for name, exp, content in extra:
        out.append("\t".join([name, exp, content]))
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("wrote %s (%d fixtures)" % (OUT, len(out) - 3))


main()
